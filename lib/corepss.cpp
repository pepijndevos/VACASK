PssCore::PssCore(
    OutputDescriptorResolver& parentResolver,
    PssParameters& params,
    Circuit& circuit,
    CommonData& commons,
    KluRealMatrix& jacobian,
    VectorRepository<double>& solution,
    VectorRepository<double>& states,
    OperatingPointCore& opCore,
    TranCore& stabilTran,
    PssTranCore& pssTran
) : AnalysisCore(parentResolver, circuit, commons),
    params(params),
    jacobian(jacobian),
    solution(solution),
    states(states),
    opCore_(opCore),
    stabilTran_(stabilTran),
    pssTran_(pssTran),
    T0_converged_(0.0)
{
    // Slot 3 is for ICs in continuation mode
    opCore_.solver().resizeForces(4);
    stabilTran_.solver().resizeForces(4);
}

