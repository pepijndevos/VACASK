// ----------------------------------------------------------------

// Called after rebuild()
bool PssCore::evaluate(bool atIc, bool noiseModulation, int nPts, ErrorConsumer& errors) {
    double T0;
    if (atIc) {
        // A list cannot supply a period, so ic must name a stored solution
        if (params.stabilParams.ic.type()!=Value::Type::String) {
            errors.push(PssSolveIcType{});
            return false;
        }
        String& solutionName = params.stabilParams.ic.val<String>();
        auto solPtr = circuit.storedSolution(solutionName);
        if (!solPtr || solPtr->typeTag()!=OperatingPointCore::solutionTag) {
            errors.push(PssIcNotFound{});
            return false;
        }
        T0 = solPtr->auxReal();
        if (T0<=0) {
            errors.push(PssTperInvalid{});
            return false;
        }

        // Map the stored solution onto the current unknowns by name (slot 3,
        // shared with the continuation IC forces)
        auto n = circuit.unknownCount();
        auto& options = circuit.simulatorOptions().core();
        if (!stabilTran_.solver().setForces(3, *solPtr, options.strictforce, errors)) {
            if (options.strictforce) {
                errors.push(PssForcesFailed{});
                return false;
            }
            Simulator::wrn() << "Warning, setting IC forces from stored solution failed.\n";
        }

        // Unknowns missing from the stored solution are an error with strictforce, otherwise a warning
        auto& forced = stabilTran_.solver().forces(3).unknownForced_;
        for(decltype(n) u=1; u<=n; u++) {
            if (!forced[u]) {
                PssIcIncomplete err{circuit.reprNode(u)->name()};
                if (options.strictforce) {
                    errors.push(std::move(err));
                    return false;
                }
                Simulator::wrn() << "Warning, " << err.format() << "\n";
                break;
            }
        }

        x0 = stabilTran_.solver().forces(3).unknownValue_;
        stabilTran_.solver().enableForces(3, false);

        // No transient has run, so the histories are not allocated yet
        // clearTrajectory() calls evalAndLoad() which in turn needs these 
        // vectors. 
        solution.upsize(2, n+1);
        states.upsize(2, circuit.statesCount());
        solution.vector() = x0;
    } else {
        // Evaluate at the current solution and the last converged period
        // (e.g. right after a converged run())
        x0 = solution.vector();
        T0 = T0_converged_;
        if (T0<=0) {
            errors.push(PssTperInvalid{});
            return false;
        }
    }

    // One-period shoot from x0, no Newton iteration
    pssTran_.setShootIC(x0);
    if (!pssTran_.clearTrajectory(errors)) {
        errors.push(PssShootingTranFailed{});
        return false;
    }
    params.shootParams.write = params.write;
    if (params.adjoint) {
        pssTran_.enableTrajectoryCapture();
    }

    // Compute max timestep
    prepareShoot(T0);

    // If nPts<=0 we compute our own value
    double nPtsNeeded = nPts;
    if (nPts<=0) {
        nPtsNeeded = std::ceil(T0/params.shootParams.maxstep);
    }

    // Round up to power of 2
    auto p2 = std::ceil(std::log2(nPtsNeeded));
    if (p2>31) {
        errors.push(PssTooManyShootingPoints{});
        return false;
    }
    nPts = static_cast<Int>(1) << static_cast<Int>(p2);

    // Needed so noise state is fresh at every timepoint, including t=0
    auto savedEvalnoise = params.shootParams.evalnoise;
    params.shootParams.evalnoise = noiseModulation;

    // Prepare for recording the time-domain Jacobians
    pssTran_.enableTdJacobianCapture(T0, nPts, noiseModulation);

    auto shootOk = runShoot(errors);

    // Disable recoring
    pssTran_.disableTdJacobianCapture();
    params.shootParams.evalnoise = savedEvalnoise;

    // Shoot OK?
    if (!shootOk) {
        // runShoot() sets the error code
        return false;
    }
    xT = solution.vector();
    phiT_ = pssTran_.phiCurrent();

    if (params.adjoint && !pssTran_.integrateAdjointMonodromy(omegaT_, errors)) {
        errors.push(PssAdjointFailed{});
        return false;
    }

    x0_converged_ = x0;
    T0_converged_ = T0;
    return true;
}

const Vector<double>& PssCore::noiseExponents() const {
    auto [tdNoiseMod, tdNoiseExp] = pssTran_.capturedNoiseModulation();
    return tdNoiseExp;
}

// ----------------------------------------------------------------
// getFrequencyDomainJacobians
// ----------------------------------------------------------------

bool PssCore::getFrequencyDomainJacobians(CSCBlockSparseComplexMatrix& jacSpec, int maxFreqIndex, Vector<Complex>* noiseModulationSpec, ErrorConsumer& errors) {
    // Get stored Jacobians
    auto [jG, jC] = pssTran_.capturedJacobians();

    // Extract the number of points
    auto nPts = pssTran_.jacobianPointCount();

    // Get period
    auto T0 = T0_converged_;

    // nPts must be even, raise exception if this does not hold
    if (nPts % 2 != 0) {
        throw std::logic_error("PssCore::getFrequencyDomainJacobians(): nPts must be even.");
    }

    // N = 2k = nPts points result in a spectrum with N=2k freq components
    // For real points X_i = X_{N-1}^*
    // Therefore X_{N/2} is conjugate to itself, i.e. real. 
    // Components X_0 .. X_{N/2-1} are the available spectrum
    // i.e. N/2 spectral components including DC (i=0). 
    // nFreq must therefore satisfy nFreq<=nPts/2
    // Caller must check if this holds.
    // Logic error otherwise
    if (maxFreqIndex >= nPts/2) {
        errors.push(PssMaxFreqIndexTooLarge{});
        return false;
    }

    // FFTW takes the length as int
    if (nPts > std::numeric_limits<int>::max()) {
        errors.push(PssTooManyShootingPoints{});
        return false;
    }

    // Temporary arrays for FFTW. G and C samples/spectra sit back to back
    // (offset nPts / nPts/2+1) so a single fftw_plan_many_dft_r2c call
    // transforms both in one pass.
    Vector<double> tdSamples(2*nPts);
    Vector<Complex> fdSamples(2*(nPts/2+1));
    auto nFd = nPts/2+1;

    // Plan FFT: 2 transforms of length nPts, consecutive in both arrays
    int fftLen[] = { static_cast<int>(nPts) };
    auto fftPlan = FftwPlan(fftw_plan_many_dft_r2c(
        1, // 1D
        fftLen, 2, // 2 vectors
        tdSamples.data(), nullptr, 1, nPts, // straightforward array, stride within arrays, array distance,
        reinterpret_cast<fftw_complex*>(fdSamples.data()), nullptr, 1, nFd, // same as for input arrays
        FFTW_ESTIMATE // fast planning
    ));
    if (!fftPlan) {
        errors.push(PssFftPlanFailed{});
        return false;
    }

    // Noise modulation function spectra, one block of maxFreqIndex+1 components per slot
    if (noiseModulationSpec) {
        auto [tdNoiseMod, tdNoiseExp] = pssTran_.capturedNoiseModulation();
        auto nSlots = circuit.noiseModulationSlotsCount();
        if (tdNoiseMod.size() != static_cast<size_t>(nSlots)*nPts) {
            throw std::logic_error("PssCore::getFrequencyDomainJacobians(): noise modulation samples not captured, call evaluate() with noiseModulation=true.");
        }

        Vector<double> noiseTdSamples(nPts);
        Vector<Complex> noiseFdSamples(nFd);
        auto noiseFftPlan = FftwPlan(fftw_plan_dft_r2c_1d(
            static_cast<int>(nPts),
            noiseTdSamples.data(),
            reinterpret_cast<fftw_complex*>(noiseFdSamples.data()),
            FFTW_ESTIMATE
        ));
        if (!noiseFftPlan) {
            errors.push(PssFftPlanFailed{});
            return false;
        }

        auto specStride = maxFreqIndex+1;
        for (decltype(nSlots) slot = 0; slot < nSlots; slot++) {
            for (decltype(nPts) t = 0; t < nPts; t++) {
                noiseTdSamples[t] = tdNoiseMod[slot*nPts + t];
            }
            fftw_execute(noiseFftPlan.get());
            for (decltype(maxFreqIndex) k = 0; k <= maxFreqIndex; k++) {
                (*noiseModulationSpec)[slot*specStride + k] = noiseFdSamples[k] / static_cast<double>(nPts);
            }
        }
    }

    // Loop through jacSpec entries, compute FD Jacobians
    auto& positions = circuit.sparsityMap().positions();
    auto nnz = positions.size();
    for (MatrixEntryIndex nzIndex = 0; nzIndex < positions.size(); nzIndex++) {
        auto& [pos, flags] = positions[nzIndex];
        if ((flags & EntryFlags::EntryType) == EntryFlags::Delay) {
            continue;
        }

        // Get FD Jacobian dense block, column 0 is G, column 1 is C
        auto [fdBlock, fdPos, fdFlags] = jacSpec.blockFromIndex(nzIndex);
        auto GCol = fdBlock.column(0);
        auto CCol = fdBlock.column(1);

        // Copy resistive and reactive samples, FFT both in one pass
        for (decltype(nPts) t = 0; t < nPts; t++) {
            tdSamples[t] = jG[t*nnz + nzIndex];
            tdSamples[nPts + t] = jC[t*nnz + nzIndex];
        }
        fftw_execute(fftPlan.get());

        // FFTW produces two-sided spectrum (we get only the right side) scaled by N
        // Normalize (FFTW's r2c is unnormalized) and store the 
        // nonnegative half of the one-sided spectrum. 
        for (decltype(maxFreqIndex) k = 0; k <= maxFreqIndex; k++) {
            GCol[k] = fdSamples[k] / static_cast<double>(nPts);
            CCol[k] = fdSamples[nFd + k] / static_cast<double>(nPts);
        }
    }


    return true;
}

// ----------------------------------------------------------------
// Phase constraint
// ----------------------------------------------------------------

void PssCore::computePhaseConstraint(
    const Vector<double>& x0,
    const Vector<double>& x1,
    double h0,
    Vector<double>& alpha
) {
    // alpha is the phase-pinning vector. The augmented Newton row
    //   alpha^T * dx0 = 0
    // constrains the correction dx0 to be perpendicular to alpha, so the
    // Newton step does not move along the phase direction (the null space of
    // (I - PhiT)). alpha must not be in the image of (I - PhiT), so it should
    // be proportional to xdot_s(t0), the circuit velocity at t0.
    //
    // Estimated by a forward finite difference between the first two points
    // of the shoot itself (pss.md, "Choosing alpha"):
    //   alpha ~= (x1 - x0) / h0
    // This needs no extra evalAndLoad call and carries no periodicity
    // assumption, unlike reusing PsiT (a t=T quantity, only equal to
    // xdot_s(0) at convergence, and even then only up to the O(h)
    // discretization error of the last step).
    // Normalised to unit length for numerical conditioning.

    auto n = circuit.unknownCount();
    alpha.assign(n, 0.0);

    VectorView alphaView(alpha);
    alphaView.vectorPlusScaledVector(
        VectorView(const_cast<Vector<double>&>(x1), 1, n, 1), 
        VectorView(const_cast<Vector<double>&>(x0), 1, n, 1), -1.0
    );
    // alpha currently holds (x1-x0), unscaled by h0; correct the norm
    // algebraically instead of scaling the vector before measuring it.
    double norm = alphaView.norm() / h0;

    if (norm > 0.0) {
        alphaView.scale(1.0/(h0*norm));
    } else {
        alphaView.scale(1.0/h0);
        if (circuit.simulatorOptions().core().pss_debug) {
            Simulator::dbg() << "x1-x0 is zero, cannot estimate phase velocity\n";
        }
        // Degenerate first step (e.g. purely resistive circuit).
        // Fall back to pinning the first unknown.
        if (n >= 1) {
            alpha[0] = 1.0;
        }
    }
}

// ----------------------------------------------------------------
// Main Newton loop
// ----------------------------------------------------------------

CoreCoroutine PssCore::coroutine(bool continuePrevious, ErrorConsumer& errors) {

    // Disable shooting transient output
    params.shootParams.write = 0;

    auto& options = circuit.simulatorOptions().core();
    auto debug = options.pss_debug;

    initProgress(1, 0);

    auto n = circuit.unknownCount();

    zero(Fp);
    zero(alpha);
    Jp.zero();

    Int    iterIndex  = 0;
    double worstRatio = 0.0;
    double          T0;

    T0_converged_ = 0.0;
    x0_converged_.clear();
    bool converged = false;

    std::stringstream ss;
    ss << std::scientific << std::setprecision(4);

    // Stabilisation is run if tstab>0, if stabstep>0 it must be <tstab
    if (params.stabstep<0 ||
        (params.tstab>0 && params.stabstep>0 && params.stabstep>=params.tstab)
    ) {
        errors.push(PssStabstepInvalid{});
        co_yield CoreState::Aborted;
    }

    // Stabilisation transient, determine initial period from parameters and stored solution
    auto [okStabil, period] = runStabilisation(continuePrevious, errors);
    if (!okStabil) {
        co_yield CoreState::Aborted;
    }
    // Require tper>0
    if(period <= 0) {
        errors.push(PssTperInvalid{});
        co_yield CoreState::Aborted;
    }

    // x_0^(0) is the state of the circuit after running the stabilisation transient
    x0 = solution.vector();
    T0 = period;

    // Continue mode
    //   Have stored solution
    //     Take T0 from solution
    //   No stored solution
    //     Use whatever is in T0
    // Ordinary mode
    //   


    // Obtain x_T^(0) by running a transient simulation for T_0 seconds
    solution.vector() = x0;
    pssTran_.setShootIC(x0);
    if (!pssTran_.clearTrajectory(errors)) {
        errors.push(PssShootingTranFailed{});
        co_yield CoreState::Aborted;
    }
    // No external maxHarm and maxFreq requested
    prepareShoot(T0);
    if (!runShoot(errors)) {
        // runShoot() sets the error code
        co_yield CoreState::Aborted;
    }
    xT = solution.vector();

    // PSS-SHOOT main loop (outer NR)
    while (iterIndex < options.pss_itl) {
        if (debug>0){
            ss.str(""); 
            ss << "PSS: shoot l=" << iterIndex << "\n";
            ss << "\tx0=[";
            auto n = circuit.unknownCount();
            for (decltype(n) i = 1; i <= n; i++) ss << " " << x0[i];
            ss << " ]\n" << "\txT=[";
            for (decltype(n) i = 1; i <= n; i++) ss << " " << xT[i];
            ss << " ]\n";
            if (params.oscillator) {
                ss << "\tT0=" << T0 << "\n";
            }
            Simulator::dbg() << ss.str();
        }

        // Obtain sensitivity matrices
        if (!pssTran_.phiValid(errors)) {
            errors.push(PssSensitivityFailed{});
            co_yield CoreState::Aborted;
        }
        auto& tmpPhiT = pssTran_.phiCurrent();
        if (debug>0) {
            ss.str(""); 
            auto n = circuit.unknownCount();
            ss << "\tPhiT=\n";
            for (decltype(n) i = 0; i < n; i++) {
                ss << "\t  [ ";
                for (decltype(n) j = 0; j < n; j++) ss << tmpPhiT.at(i, j) << " ";
                ss << "]\n";
            }
            if(params.oscillator) {
                auto& tmpPsiT = pssTran_.psiCurrent();
                ss << "\tPsiT=[ ";
                for (decltype(n) i = 0; i < n; i++) ss << tmpPsiT[i] << " ";
                ss << "]\n";
            }
            Simulator::dbg() << ss.str();
        }

        // Compute the residual (skip the bucket at x[0])
        VectorView(Fp, n).vectorPlusScaledVector(
            VectorView(x0, 1, n, 1), 
            VectorView(xT, 1, n, 1), -1.0
        );

        // Jacobian: I - PhiT (n x n block of the (n+1) x (n+1) augmented Jp)
        // Both Jp and tmpPhiT are column-major, so the block view below is
        // stride-1 within a column (colStride_=n+1, padded past row n).
        DenseMatrixView<double> jpBlock(Jp.data().data(), n, n, 1, n+1);
        jpBlock.scaledMatrix(tmpPhiT, -1.0);
        jpBlock.diagonal().addScaled(VectorView(ones_), 1.0);

        // Compute phase constraint for autonomous circuits
        if (params.oscillator){
            auto& tmpPsiT = pssTran_.psiCurrent();
            computePhaseConstraint(x0, pssTran_.firstStepX(), pssTran_.firstStepH(), alpha);
            if (debug>0){
                ss.str("");
                ss << "\talpha=[ ";
                for (decltype(n) i = 0; i < n; i++) ss << alpha[i] << " ";
                ss << "]\n";
                Simulator::dbg() << ss.str();
            }
            // Add alpha^Tx_0 to the Fp map
            Fp[n] = 0;
            // Residual of the phase condition equation is 0 because
            // we are forcing orthogonality of the solver step. 
            // Augment the Jacobian
            // Right column: PsiT
            Jp.column(n).subVector(0, n).scaledVector(VectorView(tmpPsiT), -1.0);
            // Bottom row: alpha^T
            Jp.row(n).subVector(0, n) = VectorView(alpha);
        }
        // If the circuit is driven, make sure Jp is not singular by setting the corner to 1
        Jp.at(n, n) = !params.oscillator ? 1.0 : 0.0;

        // Solve the Newton step
        VectorView rhsView(Fp);
        VectorView rowPermView(rowPerm_);
        if (!Jp.factorAndLuSolve(rhsView, &rowPermView)) {
             errors.push(PssSingularJacobian{});
             co_yield CoreState::Aborted;
        }
        // Update x0 and T0
        VectorView(x0, 1, n, 1).addScaled(
            VectorView(Fp, n), -1.0
        );
        T0 -= !params.oscillator ? 0.0 : rhsView[n];

        // Get new xT
        solution.vector() = x0;
        pssTran_.setShootIC(x0);
        if (!pssTran_.clearTrajectory(errors)) {
            errors.push(PssShootingTranFailed{});
            co_yield CoreState::Aborted;
        }
        prepareShoot(T0);
        if (!runShoot(errors)) {
            // runShoot() sets the error code
            co_yield CoreState::Aborted;
        }
        xT = solution.vector();

        // Convergence check: per-unknown shooting residual vs SPICE delta tolerance.
        // A (used): tol[i] = pss_tolscale * max(|x0[i]|*reltol, abstol[i]) -- matches OP/TRAN
        //   checkDelta; scales with signal magnitude so large/small nodes converge proportionally.
        // pss_tolscale should be >=1. One cannot expect stricter tolerance from PSS 
        // than from underlying op/tran. 
        bool shootConverged = true;
        worstRatio = 0.0;
        for (decltype(n) i = 1; i <= n; i++) {
            double tol = options.pss_tolscale *
                         std::max(std::fabs(x0[i]) * options.reltol, commons.unknown_abstol[i]);
            double ratio = std::fabs(x0[i] - xT[i]) / tol;
            if (ratio > worstRatio) worstRatio = ratio;
            if (ratio > 1.0) shootConverged = false;
        }
        if (debug>0){
            ss.str("");
            ss << "\tworst residual ratio= " << worstRatio << "\n";
            Simulator::dbg() << ss.str();
        }

        if (shootConverged) {
            converged = true;
            break;
        } else {
            iterIndex++;
        }
    } // end PSS-SHOOT main loop
    
    if (!converged) {
        errors.push(PssNoConvergence{options.pss_itl});
        co_yield CoreState::Aborted;
    }

    // Store converged monodromy
    phiT_ = pssTran_.phiCurrent();

    if (converged && params.store.length()>0) {
        auto& sol = circuit.newStoredSolution(params.store);
        sol.setTypeTag(OperatingPointCore::solutionTag);
        sol.setNames(circuit);
        sol.setValues(solution.vector());
        sol.setAuxReal(T0);
    }

    if (debug>0) {
        Simulator::dbg() << "PSS analysis finshed.\n";
        ss.str("");
        ss << "Converged in " << iterIndex + 1 << " iterations.\n";
        ss << "Final worst residual ratio = " << worstRatio << "\n";
        Simulator::dbg() << ss.str();
    }

    // Enable writing for last run of shooting transient
    params.shootParams.write = params.write;
    
    solution.vector() = x0;
    pssTran_.setShootIC(x0);
    if (!pssTran_.clearTrajectory(errors)) {
        errors.push(PssShootingTranFailed{});
        co_yield CoreState::Aborted;
    }
    // Only capture trajectory if we intend to calculate the adjoint monodromy matrix
    if (params.adjoint) {
        pssTran_.enableTrajectoryCapture();
    }
    prepareShoot(T0);
    if (!runShoot(errors)) {
        co_yield CoreState::Aborted;
    }

    // Integrate Omega backward using captured trajectory
    if (params.adjoint) {
        if ( !pssTran_.integrateAdjointMonodromy(omegaT_, errors)) {
            errors.push(PssAdjointFailed{});
            co_yield CoreState::Aborted;
        
        }
    }

    if (debug>0) {
        ss.str(""); 
        auto n = circuit.unknownCount();
        ss << "-- Monodromy --\n";
        ss << "\tPhi(T,0) =\n";
        for (decltype(n) i = 0; i < n; i++) {
            ss << "\t  [ ";
            for (decltype(n) j = 0; j < n; j++) ss << pssTran_.phiCurrent().at(i, j) << " ";
            ss << "]\n";
        }
        if (params.adjoint) {
            ss << "\tOmega(T,0) =\n";
            for (decltype(n) i = 0; i < n; i++) {
                ss << "\t  [ ";
                for (decltype(n) j = 0; j < n; j++) ss << omegaT_.at(i, j) << " ";
                ss << "]\n";
            }
        }
        Simulator::dbg() << ss.str();
    }
    
    x0_converged_ = x0;
    T0_converged_ = T0;
    setProgress(1);
    co_yield CoreState::Finished;
    
}

bool PssCore::run(bool continuePrevious, ErrorConsumer& errors) {
    auto c = coroutine(continuePrevious, errors);
    bool ok = true;
    while (!c.done()) {
        if (c.resume() == CoreState::Aborted) {
            ok = false;
            break;
        }
    }
    return ok;

}

std::tuple<bool, const DenseMatrix<double>&> PssCore::convergedAdjointMonodromy(ErrorConsumer& errors) {
    if (!params.adjoint) {
        errors.push(PssAdjointDisabled{});
        return std::make_tuple(false, omegaT_);
    }
    return std::make_tuple(true, omegaT_);
}

void PssCore::dump(std::ostream& os) const {
    AnalysisCore::dump(os);
    os << "  Converged period: " << T0_converged_ << " s\n";
    os << "  Converged frequency: "
       << (T0_converged_ > 0 ? 1.0 / T0_converged_ : 0.0) << " Hz\n";
}

