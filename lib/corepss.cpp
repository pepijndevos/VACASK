bool PssCore::rebuild(ErrorConsumer& errors) {
    auto& options = circuit.simulatorOptions().core();

    // Check if any device has delays
    if (circuit.usesIllegalDeviceFeatures(DeviceFlags::Absdelay, DeviceFlags::None, errors)) {
        errors.push(PssCircuitUsesUnsupportedFeatures{});
        return false;
    }

    // Tran IC forces
    stabilTran_.solver().setForcesFactor(3, options.nr_force);
    // OP IC forces
    opCore_.solver().setForcesFactor(3, options.nr_force);

    auto n = circuit.unknownCount();
    Fp.resize(n+1);
    alpha.resize(n);
    // We are going to solve a linear system with this matrix. 
    // Make it column major. 
    Jp.resize(n+1, n+1, DenseMatrix<double>::Major::Column);
    rowPerm_.resize(n+1);
    ones_.assign(n, 1.0);
    x0.resize(n+1);
    xT.resize(n+1);

    // Get ic, if it is a stored solution, extract its period

    return true;
}

bool PssCore::initializeOutputs(Id name, ErrorConsumer& errors) {
    // Store the name for use when the output file is opened after convergence.
    // Do NOT open the pssTran_ raw file here: it must be opened only once,
    // after the Newton loop converges, so that intermediate shooting iterations
    // do not pollute the output.
    name_ = name;
    return true;
}

bool PssCore::finalizeOutputs(ErrorConsumer& errors) {
    return pssTran_.finalizeOutputs(errors);
}

bool PssCore::deleteOutputs(Id name, ErrorConsumer& errors) {
    if (!params.write || Simulator::noOutput()) {
        return true;
    }
    // Cannot assume outfile is available
    auto fname = std::string(name)+".raw";
    std::error_code ec;
    std::filesystem::remove(fname, ec);
    return true;
}

bool PssCore::storeState(size_t ndx, bool storeDetails) {
    auto& repo = coreStates.at(ndx);
    repo.solution.setTypeTag(OperatingPointCore::solutionTag);

    // Store current solution as annotated solution
    if (storeDetails) {
        repo.solution.setNames(circuit);
    } else {
        repo.solution.clearNames();
    }
    
    // Store time domain solution
    repo.solution.setValues(solution.vector());
    
    // Store period
    repo.solution.setAuxReal(T0_converged_);

    // Stored state is coherent and valid
    repo.coherent = true;
    repo.valid = true;
    return true;
}

bool PssCore::restoreState(size_t ndx) {
    auto& state = coreStates.at(ndx);
    if (state.valid) {
        // State is valid
        continueState = &state;
        return true;
    } else { 
        // Nothing to restore, do not use continuation mode
        return false;
    }
}

